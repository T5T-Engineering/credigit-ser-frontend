#!/usr/bin/env node
/**
 * Regenerates the frontend copy of the Identity & Access permission catalogue (invariant 12, ADR-0012).
 *
 *   node scripts/sync-permissions.mjs [backendConfigDir]
 *
 * Reads `permissions.json` and `roles.json` from the backend host config (default:
 * ../credigit-ser-core-backend/src/Host.Credigit.Risk360.Api/config, or $CREDIGIT_BACKEND_CONFIG) and writes:
 *   - src/lib/iam/permission-catalogue.json  (catalogue, baseline, protected patterns, role defaults)
 *   - src/lib/iam/permission-keys.ts         (the PermissionKey union type)
 * Never hand-edit the generated files; re-run this script when the backend catalogue changes.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const configDir = resolve(process.argv[2] ?? process.env.CREDIGIT_BACKEND_CONFIG ?? join(root, "..", "credigit-ser-core-backend", "src", "Host.Credigit.Risk360.Api", "config"));

const read = (name) => JSON.parse(readFileSync(join(configDir, name), "utf8"));
const perms = read("permissions.json").IdentityAccess.Permissions;
const roles = read("roles.json").IdentityAccess.Roles;

const permissions = perms.Catalogue.map((p) => ({
  key: p.Key,
  label: p.Label,
  description: p.Description,
  module: p.Module,
  group: p.Group,
  sensitive: Boolean(p.Sensitive),
  area: p.Area,
  level: p.Level === "edit" ? "edit" : "view",
}));
const keys = permissions.map((p) => p.key);
const dupes = keys.filter((k, i) => keys.indexOf(k) !== i);
if (dupes.length) throw new Error(`Duplicate permission keys: ${dupes.join(", ")}`);

const roleDefaults = roles.map((r) => ({
  id: r.Id,
  modules: r.Modules ?? {},
  grantsAllPermissions: Boolean(r.GrantsAllPermissions),
  extraPermissions: r.ExtraPermissions ?? [],
}));
for (const r of roleDefaults) for (const k of r.extraPermissions) if (!keys.includes(k)) throw new Error(`Role ${r.id}: unknown extra permission ${k}`);

const body = { permissions, baseline: perms.Baseline, protectedAdministratorPermissions: perms.ProtectedAdministratorPermissions, roleDefaults };
const version = createHash("sha256").update(JSON.stringify(body)).digest("hex").slice(0, 12);
const out = { $comment: "GENERATED by scripts/sync-permissions.mjs from the backend config/permissions.json and config/roles.json. Do not edit.", version, ...body };

writeFileSync(join(root, "src", "lib", "iam", "permission-catalogue.json"), `${JSON.stringify(out, null, 2)}\n`);
writeFileSync(
  join(root, "src", "lib", "iam", "permission-keys.ts"),
  `// GENERATED by scripts/sync-permissions.mjs — do not edit. Catalogue version ${version} (${keys.length} permissions).\n` +
    `/** A key of the Identity & Access permission catalogue (\`<module>.<resource>.<action>\`). */\n` +
    `export type PermissionKey =\n${keys.map((k) => `  | ${JSON.stringify(k)}`).join("\n")};\n`,
);
console.log(`Permission catalogue ${version}: ${keys.length} permissions, ${roleDefaults.length} roles → src/lib/iam/`);
